/** Seeds demo data once (per seed version). Safe to call on every boot. */
export async function ensureSeeded(): Promise<void> {
  const seeded = load<number>(STORAGE_KEYS.seeded, 0)
  if (seeded >= SEED_VERSION) return
  const [users] = await Promise.all([seedUsers()])
  save(STORAGE_KEYS.users, users)
  save(STORAGE_KEYS.companies, seedCompanies())
  save(STORAGE_KEYS.inquiries, seedInquiries())
  save(STORAGE_KEYS.seeded, SEED_VERSION)
}

export async function resetDemoData(): Promise<void> {
  save(STORAGE_KEYS.seeded, 0)
  localStorage.removeItem(STORAGE_KEYS.session)
  localStorage.removeItem(STORAGE_KEYS.draft)
  localStorage.removeItem(STORAGE_KEYS.contact)
  await ensureSeeded()
}
