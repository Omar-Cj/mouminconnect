const SEED_VERSION = 3

const daysAgo = (d: number, h = 0) => new Date(Date.now() - d * 86_400_000 - h * 3_600_000).toISOString()
const daysAhead = (d: number, h = 0) => new Date(Date.now() + d * 86_400_000 + h * 3_600_000).toISOString()

const ADMIN_ID = 'u_admin'
const ADMIN_NAME = 'MBC Admin'

const act = (id: string, type: Activity['type'], text: string, at: string, byId = ADMIN_ID, byName = ADMIN_NAME): Activity => ({
  id,
  type,
  text,
  at,
  byId,
  byName,
})
const msg = (id: string, fromId: string, fromName: string, fromRole: 'admin' | 'customer', text: string, at: string): Message => ({
  id,
  fromId,
  fromName,
  fromRole,
  text,
  at,
})
const note = (id: string, text: string, at: string): Note => ({ id, text, at, byId: ADMIN_ID, byName: ADMIN_NAME })

